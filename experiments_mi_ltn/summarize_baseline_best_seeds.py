#!/usr/bin/env python
"""Build CSV and LaTeX summaries for the selected EEGNet baseline seed runs."""

from __future__ import annotations

import csv
import json
from pathlib import Path


RUN_ROOT = Path("experiments_mi_ltn/runs/baseline_eegnet")
OUTPUT_CSV = RUN_ROOT / "best_seeds_summary.csv"
OUTPUT_TEX = RUN_ROOT / "best_seeds_results_table.tex"

REFERENCE_RUN_ID = "eegnet_lr5e-4_seed42_ep300_es50"
TARGET_RUN_IDS = {
    0: "eegnet_best_lr5e-4_seed0_ep300_es50",
    7: "eegnet_best_lr5e-4_seed7_ep300_es50",
    123: "eegnet_best_lr5e-4_seed123_ep300_es50",
    2024: "eegnet_best_lr5e-4_seed2024_ep300_es50",
}

FIELDNAMES = [
    "run_id",
    "model",
    "seed",
    "epochs",
    "lr",
    "batch_size",
    "weight_decay",
    "scheduler",
    "early_stopping_patience",
    "best_val_acc",
    "best_epoch",
    "final_train_acc",
    "final_val_acc",
    "checkpoint_best_path",
    "history_csv",
    "summary_json",
    "status",
    "notes",
]


def read_json(path: Path) -> dict | None:
    if not path.exists():
        return None
    with path.open() as f:
        return json.load(f)


def read_final_metrics(history_csv: Path) -> tuple[str, str]:
    if not history_csv.exists():
        return "", ""
    with history_csv.open(newline="") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        return "", ""
    last = rows[-1]
    return last.get("train_acc", ""), last.get("val_acc", "")


def row_for_run(run_id: str, seed: int, reference: bool = False) -> dict:
    run_dir = RUN_ROOT / run_id
    summary_path = run_dir / "summary.json"
    args_path = run_dir / "args.json"
    summary = read_json(summary_path)
    args = read_json(args_path) or {}

    if summary is None:
        return {
            "run_id": run_id,
            "model": "EEGNet",
            "seed": seed,
            "epochs": 300,
            "lr": "0.0005",
            "batch_size": 64,
            "weight_decay": "0.0",
            "scheduler": "none",
            "early_stopping_patience": 50,
            "best_val_acc": "",
            "best_epoch": "",
            "final_train_acc": "",
            "final_val_acc": "",
            "checkpoint_best_path": "",
            "history_csv": str(run_dir / "history.csv"),
            "summary_json": str(summary_path),
            "status": "pending",
            "notes": "not run yet",
        }

    history_csv = Path(summary.get("history_csv", run_dir / "history.csv"))
    if not history_csv.exists():
        history_csv = run_dir / "history.csv"
    final_train_acc, final_val_acc = read_final_metrics(history_csv)
    notes = "seed 42 reference from phase 1" if reference else ""

    return {
        "run_id": run_id,
        "model": summary.get("model", "EEGNet"),
        "seed": summary.get("seed", args.get("seed", seed)),
        "epochs": summary.get("epochs_completed", args.get("epochs", "")),
        "lr": summary.get("learning_rate", args.get("learning_rate", "")),
        "batch_size": summary.get("batch_size", args.get("batch_size", "")),
        "weight_decay": summary.get("weight_decay", args.get("weight_decay", "")),
        "scheduler": summary.get("scheduler", args.get("scheduler", "")),
        "early_stopping_patience": summary.get(
            "early_stopping_patience", args.get("early_stopping_patience", "")
        ),
        "best_val_acc": summary.get("best_val_acc", ""),
        "best_epoch": summary.get("best_epoch", ""),
        "final_train_acc": final_train_acc,
        "final_val_acc": final_val_acc,
        "checkpoint_best_path": summary.get("checkpoint_best_path", ""),
        "history_csv": str(history_csv),
        "summary_json": str(summary_path),
        "status": summary.get("status", "completed"),
        "notes": notes,
    }


def fmt_acc(value: object) -> str:
    if value in ("", None):
        return "--"
    return f"{float(value):.4f}"


def fmt_value(value: object) -> str:
    if value in ("", None):
        return "--"
    return str(value)


def write_csv(rows: list[dict]) -> None:
    RUN_ROOT.mkdir(parents=True, exist_ok=True)
    with OUTPUT_CSV.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
        writer.writeheader()
        writer.writerows(rows)


def write_tex(rows: list[dict]) -> None:
    lines = [
        "% Auto-generated by experiments_mi_ltn/summarize_baseline_best_seeds.py",
        "\\begin{tabular}{rrrrr}",
        "\\toprule",
        "Seed & Best val. acc. & Best epoch & Final train acc. & Final val. acc. \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            f"{row['seed']} & {fmt_acc(row['best_val_acc'])} & "
            f"{fmt_value(row['best_epoch'])} & {fmt_acc(row['final_train_acc'])} & "
            f"{fmt_acc(row['final_val_acc'])} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    OUTPUT_TEX.write_text("\n".join(lines))


def main() -> None:
    rows = [row_for_run(REFERENCE_RUN_ID, 42, reference=True)]
    rows.extend(row_for_run(run_id, seed) for seed, run_id in TARGET_RUN_IDS.items())
    write_csv(rows)
    write_tex(rows)
    print(f"Wrote {OUTPUT_CSV}")
    print(f"Wrote {OUTPUT_TEX}")


if __name__ == "__main__":
    main()
