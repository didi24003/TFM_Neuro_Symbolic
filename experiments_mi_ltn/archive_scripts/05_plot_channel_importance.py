#!/usr/bin/env python
"""Plot EEG channel importance from the permutation ranking CSV."""

from __future__ import annotations

import argparse
import csv
import os
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
RUNS_DIR = SCRIPT_DIR / "runs"
MPLCONFIG_DIR = RUNS_DIR / ".matplotlib"
MPLCONFIG_DIR.mkdir(parents=True, exist_ok=True)
os.environ.setdefault("MPLCONFIGDIR", str(MPLCONFIG_DIR))

import matplotlib.pyplot as plt


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input-csv",
        type=Path,
        default=RUNS_DIR / "channel_importance.csv",
        help="CSV generated by 03_channel_importance.py.",
    )
    parser.add_argument(
        "--output-csv",
        type=Path,
        default=RUNS_DIR / "channel_importance_sorted.csv",
        help="Descending ranking CSV to write.",
    )
    parser.add_argument(
        "--output-png",
        type=Path,
        default=RUNS_DIR / "channel_importance_barplot.png",
        help="Bar plot PNG to write.",
    )
    return parser.parse_args()


def load_rows(input_csv: Path) -> list[dict[str, str]]:
    if not input_csv.exists():
        raise FileNotFoundError(f"Input CSV not found: {input_csv.resolve()}")

    with input_csv.open(newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    if not rows:
        raise ValueError(f"Input CSV has no rows: {input_csv.resolve()}")
    if "importance" not in rows[0] or "channel_name" not in rows[0]:
        raise ValueError("Input CSV must contain 'channel_name' and 'importance' columns")

    return rows


def sort_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    sorted_rows = sorted(rows, key=lambda row: float(row["importance"]), reverse=True)
    for rank, row in enumerate(sorted_rows, start=1):
        if "rank" in row:
            row["rank"] = str(rank)
    return sorted_rows


def write_sorted_csv(rows: list[dict[str, str]], output_csv: Path) -> None:
    output_csv.parent.mkdir(parents=True, exist_ok=True)
    with output_csv.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def plot_importance(rows: list[dict[str, str]], output_png: Path) -> None:
    channel_names = [row["channel_name"] for row in rows]
    importance = [float(row["importance"]) for row in rows]

    fig, ax = plt.subplots(figsize=(11, 5.5))
    ax.bar(channel_names, importance, color="#4477aa")
    ax.set_xlabel("Channel")
    ax.set_ylabel("Importance (base accuracy - permuted accuracy)")
    ax.set_title("Channel importance by permutation")
    ax.tick_params(axis="x", rotation=45)
    ax.grid(axis="y", linestyle="--", alpha=0.35)
    fig.tight_layout()

    output_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_png, dpi=200)
    plt.close(fig)


def main() -> None:
    args = parse_args()
    rows = sort_rows(load_rows(args.input_csv))
    write_sorted_csv(rows, args.output_csv)
    plot_importance(rows, args.output_png)

    print(f"saved sorted CSV: {args.output_csv}")
    print(f"saved bar plot: {args.output_png}")


if __name__ == "__main__":
    main()
