#!/usr/bin/env python
"""Summarize EEGNet channel-rule lambda runs."""

from __future__ import annotations

import csv
import json
from pathlib import Path


RUN_ROOT = Path("experiments_mi_ltn/runs/eegnet_channel_rule_loss")
OUTPUT_CSV = RUN_ROOT / "channel_rule_lambdas_summary.csv"
OUTPUT_TEX = RUN_ROOT / "channel_rule_lambdas_latex_table.txt"
LAMBDAS = [0.0, 0.01, 0.05, 0.1, 0.2, 0.5, 1.0]
FIELDNAMES = [
    "lambda_rule",
    "run_id",
    "best_val_acc",
    "best_epoch",
    "final_train_acc",
    "final_val_acc",
    "R_SM",
    "R_POST",
    "R_SM_minus_POST",
    "overfit_gap",
    "status",
    "notes",
]


def read_json(path: Path) -> dict | None:
    if not path.exists():
        return None
    with path.open() as f:
        return json.load(f)


def fmt_float(value: object) -> str:
    if value in ("", None):
        return "--"
    return f"{float(value):.4f}"


def lambda_key(value: float) -> str:
    text = f"{value:.12f}".rstrip("0").rstrip(".")
    if "." not in text:
        text = f"{text}.0"
    return text


def lambda_from_summary(summary: dict) -> float | None:
    value = summary.get("lambda_rule")
    if value in ("", None):
        return None
    return float(value)


def candidate_run_dirs() -> list[Path]:
    if not RUN_ROOT.exists():
        return []
    return sorted(
        [path for path in RUN_ROOT.iterdir() if path.is_dir() and (path / "summary.json").exists()],
        key=lambda path: (path.stat().st_mtime, path.name),
        reverse=True,
    )


def select_runs() -> dict[str, tuple[Path, dict]]:
    selected: dict[str, tuple[Path, dict]] = {}
    for run_dir in candidate_run_dirs():
        summary = read_json(run_dir / "summary.json")
        if summary is None:
            continue
        lambda_value = lambda_from_summary(summary)
        if lambda_value is None:
            continue
        key = lambda_key(lambda_value)
        selected.setdefault(key, (run_dir, summary))
    return selected


def summary_metric(summary: dict, primary_key: str, fallback_key: str) -> object:
    value = summary.get(primary_key)
    if value not in ("", None):
        return value
    return summary.get(fallback_key, "")


def row_for_lambda(lambda_value: float, selected: dict[str, tuple[Path, dict]]) -> dict:
    key = lambda_key(lambda_value)
    if key not in selected:
        return {
            "lambda_rule": lambda_value,
            "run_id": f"lambda_{key}_seed2024",
            "best_val_acc": "",
            "best_epoch": "",
            "final_train_acc": "",
            "final_val_acc": "",
            "R_SM": "",
            "R_POST": "",
            "R_SM_minus_POST": "",
            "overfit_gap": "",
            "status": "pending",
            "notes": "summary.json not found yet",
        }

    run_dir, summary = selected[key]
    final_train_acc = summary.get("final_train_acc", "")
    final_val_acc = summary.get("final_val_acc", "")
    overfit_gap = ""
    if final_train_acc not in ("", None) and final_val_acc not in ("", None):
        overfit_gap = float(final_train_acc) - float(final_val_acc)
    return {
        "lambda_rule": float(summary.get("lambda_rule", lambda_value)),
        "run_id": run_dir.name,
        "best_val_acc": summary.get("best_val_acc", ""),
        "best_epoch": summary.get("best_epoch", ""),
        "final_train_acc": final_train_acc,
        "final_val_acc": final_val_acc,
        "R_SM": summary_metric(summary, "R_SM", "final_r_sm"),
        "R_POST": summary_metric(summary, "R_POST", "final_r_post"),
        "R_SM_minus_POST": summary_metric(summary, "R_SM_minus_POST", "final_r_diff"),
        "overfit_gap": overfit_gap,
        "status": summary.get("status", "completed"),
        "notes": "",
    }


def write_csv(rows: list[dict]) -> None:
    RUN_ROOT.mkdir(parents=True, exist_ok=True)
    with OUTPUT_CSV.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
        writer.writeheader()
        writer.writerows(rows)


def write_tex(rows: list[dict]) -> None:
    lines = [
        "% Auto-generated by experiments_mi_ltn/summarize_channel_rule_lambdas.py",
        "\\begin{tabular}{rrrrrrrr}",
        "\\toprule",
        "$\\lambda_{rule}$ & Best val. acc. & Best epoch & Final train acc. & Final val. acc. & $R_{SM}$ & $R_{POST}$ & $R_{SM}-R_{POST}$ \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            f"{row['lambda_rule']} & {fmt_float(row['best_val_acc'])} & {row['best_epoch'] or '--'} & "
            f"{fmt_float(row['final_train_acc'])} & {fmt_float(row['final_val_acc'])} & "
            f"{fmt_float(row['R_SM'])} & {fmt_float(row['R_POST'])} & "
            f"{fmt_float(row['R_SM_minus_POST'])} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    OUTPUT_TEX.write_text("\n".join(lines))


def best_row(rows: list[dict], metric: str) -> dict | None:
    completed = [
        row
        for row in rows
        if row.get("status") not in ("pending", "failed")
        and row.get(metric) not in ("", None)
    ]
    if not completed:
        return None
    return max(completed, key=lambda row: float(row[metric]))


def print_findings(rows: list[dict]) -> None:
    best_best = best_row(rows, "best_val_acc")
    best_final = best_row(rows, "final_val_acc")
    control = next((row for row in rows if float(row["lambda_rule"]) == 0.0), None)

    if best_best is not None:
        print(
            "best_lambda_by_best_val_acc="
            f"{best_best['lambda_rule']} run_id={best_best['run_id']} best_val_acc={best_best['best_val_acc']}"
        )
    else:
        print("best_lambda_by_best_val_acc=unavailable")

    if best_final is not None:
        print(
            "best_lambda_by_final_val_acc="
            f"{best_final['lambda_rule']} run_id={best_final['run_id']} final_val_acc={best_final['final_val_acc']}"
        )
    else:
        print("best_lambda_by_final_val_acc=unavailable")

    if control is None:
        print("control_comparison=unavailable")
    else:
        def compare_vs_control(metric: str, label: str, direction: str) -> None:
            control_value = control.get(metric)
            if control_value in ("", None):
                print(f"{label}=unavailable")
                return
            control_float = float(control_value)
            if direction == "increase":
                candidates = [
                    row for row in rows if row.get(metric) not in ("", None) and float(row[metric]) > control_float
                ]
                if candidates:
                    best_candidate = max(candidates, key=lambda row: float(row[metric]))
                    print(
                        f"{label}=improved best_lambda={best_candidate['lambda_rule']} "
                        f"control={control_float:.4f} best={float(best_candidate[metric]):.4f}"
                    )
                else:
                    print(f"{label}=no_clear_increase control={control_float:.4f}")
            else:
                candidates = [
                    row for row in rows if row.get(metric) not in ("", None) and float(row[metric]) < control_float
                ]
                if candidates:
                    best_candidate = min(candidates, key=lambda row: float(row[metric]))
                    print(
                        f"{label}=improved best_lambda={best_candidate['lambda_rule']} "
                        f"control={control_float:.4f} best={float(best_candidate[metric]):.4f}"
                    )
                else:
                    print(f"{label}=no_clear_decrease control={control_float:.4f}")

        compare_vs_control("R_SM", "r_sm_vs_control", "increase")
        compare_vs_control("R_POST", "r_post_vs_control", "decrease")
        compare_vs_control("R_SM_minus_POST", "r_diff_vs_control", "increase")

    overfit_rows = [
        row
        for row in rows
        if row.get("overfit_gap") not in ("", None) and float(row["overfit_gap"]) > 0.05
    ]
    if overfit_rows:
        joined = ", ".join(
            f"lambda={row['lambda_rule']} gap={float(row['overfit_gap']):.4f}" for row in overfit_rows
        )
        print(f"overfitting_warning={joined}")
    else:
        print("overfitting_warning=none_detected")


def main() -> None:
    selected = select_runs()
    rows = [row_for_lambda(value, selected) for value in LAMBDAS]
    write_csv(rows)
    write_tex(rows)
    print_findings(rows)
    print(f"Wrote {OUTPUT_CSV}")
    print(f"Wrote {OUTPUT_TEX}")


if __name__ == "__main__":
    main()
